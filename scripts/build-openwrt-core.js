const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'openwrt/luci-app-obhod/htdocs/luci-static/resources/obhod/core.js');
const catalogOutput = path.join(root, 'openwrt/presets.tsv');
function buildPresetCatalog() {
  const { PODKOP_PRESETS, ALLOWED_WITH_RUSSIA_INSIDE } = require('../shared/profile');
  return Object.entries(PODKOP_PRESETS).map(([id, title]) => `${id}|${title}|${ALLOWED_WITH_RUSSIA_INSIDE.includes(id) ? 1 : 0}`).join('\n') + '\n';
}

function buildCore() {
  const files = { profile: 'shared/profile.js', 'config-generator': 'shared/config-generator.js', subscription: 'shared/subscription.js', 'openwrt-config': 'openwrt/lib/config.js' };
  const modules = Object.entries(files).map(([name, source]) => `${JSON.stringify('./' + name)}: function(module, exports, require) {\n${fs.readFileSync(path.join(root, source), 'utf8').replace(/\r\n/g, '\n').replace(/require\('\.\.\/\.\.\/shared\/(profile|config-generator)'\)/g, "require('./$1')")}\n}`).join(',\n');
  return `'use strict';\n'require baseclass';\n// Generated by scripts/build-openwrt-core.js from the Apache-2.0 Obhod sources.\nreturn baseclass.extend((function() {\n` +
`const Buffer = {
  byteLength: function(value) { return new TextEncoder().encode(value).length; },
  from: function(value, encoding) {
    if (encoding !== 'base64' && encoding !== 'base64url') throw new Error('Unsupported encoding');
    const binary = atob(String(value).replace(/-/g, '+').replace(/_/g, '/').replace(/\\s/g, ''));
    const bytes = Uint8Array.from(binary, function(c) { return c.charCodeAt(0); });
    return { toString: function() { return new TextDecoder().decode(bytes); } };
  }
};
const native = {
  'node:crypto': { randomUUID: function() {
    const bytes = new Uint8Array(16); globalThis.crypto.getRandomValues(bytes);
    bytes[6] = (bytes[6] & 15) | 64; bytes[8] = (bytes[8] & 63) | 128;
    const hex = Array.from(bytes, function(b) { return b.toString(16).padStart(2, '0'); }).join('');
    return hex.slice(0,8)+'-'+hex.slice(8,12)+'-'+hex.slice(12,16)+'-'+hex.slice(16,20)+'-'+hex.slice(20);
  } },
  'node:path': { win32: {} },
  'node:net': { isIP: function(value) {
    if (/^(?:[0-9]{1,3}\\.){3}[0-9]{1,3}$/.test(value) && value.split('.').every(function(v) { return Number(v) <= 255; })) return 4;
    try { if (value.includes(':') && new URL('http://['+value+']/').hostname) return 6; } catch (_) {}
    return 0;
  } }
};
const modules = {${modules}};
const cache = {};
function require(name) {
  if (native[name]) return native[name];
  if (!modules[name]) throw new Error('Unknown module: '+name);
  if (!cache[name]) { const module = { exports: {} }; cache[name] = module; modules[name](module, module.exports, require); }
  return cache[name].exports;
}
const profile = require('./profile');
const subscriptions = require('./subscription');
const router = require('./openwrt-config');
return { defaults: router.defaultRouterProfile, generate: router.generateRouterConfig,
  validate: profile.validateConfig, presets: profile.PODKOP_PRESETS, normalizePresets: profile.normalizePresetIds, parseUri: profile.parseProxyUri,
  parseWireGuard: profile.parseWireGuardConfig, parseSubscription: subscriptions.parseSubscription,
  mergeSubscription: subscriptions.mergeSubscription };
})());\n`;
}

if (require.main === module) {
  const text = buildCore();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== text) {
      throw new Error('OpenWrt core is stale: run node scripts/build-openwrt-core.js');
    }
    if (!fs.existsSync(catalogOutput) || fs.readFileSync(catalogOutput, 'utf8').replace(/\r\n/g, '\n') !== buildPresetCatalog()) throw new Error('OpenWrt preset catalog is stale');
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true }); fs.writeFileSync(output, text);
    fs.writeFileSync(catalogOutput, buildPresetCatalog());
  }
}
module.exports = { buildCore, buildPresetCatalog };
